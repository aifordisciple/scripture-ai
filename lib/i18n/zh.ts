// This allows `zh` to use `as const` (for autocomplete of key paths) while `en` can provide
// any string values that satisfy the same structural shape.
type DeepStringify<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepStringify<T[K]>
}

